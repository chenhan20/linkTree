/* Degradation probes: (1) fx js + theme css blocked -> nine views + drawer + modal still work, hosts hidden, no atmosphere.
   (2) strava.json blocked -> Data unavailable message, no fx exceptions. */
const { launch, CDP, sleep } = require('./cdp-lib.js')
const fs = require('fs'), path = require('path')
const OUT = path.join(__dirname, 'shots')
const res = { pass: [], fail: [], console: [] }
const ok = (n, c, i) => { (c ? res.pass : res.fail).push(n + (i ? ' :: ' + i : '')); console.log((c ? '  + ' : '  - ') + n + (i ? ' :: ' + i : '')) }
;(async () => {
  const PORT = 9800 + Math.floor(Math.random() * 100)
  const chrome = await launch(PORT, 1440, 1000); const c = await CDP.open(PORT)
  await c.send('Page.enable'); await c.send('Runtime.enable'); await c.send('Network.enable'); await c.send('Log.enable'); await c.send('Network.setCacheDisabled', { cacheDisabled: true })
  c.on('Runtime.exceptionThrown', p => res.console.push('EXC ' + (p.exceptionDetails.exception && p.exceptionDetails.exception.description || p.exceptionDetails.text).split('\n')[0]))
  c.on('Runtime.consoleAPICalled', p => { if (p.type === 'error') res.console.push('ERR ' + p.args.map(a => a.value || a.description || '').join(' ').slice(0, 160)) })
  await c.viewport(1440, 1000, false)
  console.log('## no-fx (theme + fx blocked)')
  await c.send('Network.setBlockedURLs', { urls: ['*strava-fable51-fx.js*', '*theme-fable51.css*'] })
  await c.goto('http://127.0.0.1:8765/strava_fable51.html')
  ok('data-ready fired without fx', await c.waitFor('!!window.__fxData', 25000))
  await sleep(1200)
  const s = await c.eval(`({fx: !!window.__fx, fxAttr: document.documentElement.dataset.fx, atmHidden: document.getElementById('atm').hidden, hosts: [...document.querySelectorAll('.fx-host')].map(h => h.hidden && h.children.length === 0), bar: document.querySelector('#atm-bar').textContent.trim().length, ctl: !!document.querySelector('.fxm'), lab: document.getElementById('atm-lab').children.length, rdy: !!document.querySelector('.side .rdy'), nav: document.querySelectorAll('.nav-i').length, hero: !!document.getElementById('hero')})`)
  ok('fx absent, data-fx attr still set by head bootstrap', !s.fx && s.fxAttr === 'overdrive', JSON.stringify(s))
  ok('atmosphere canvas stays hidden', s.atmHidden)
  ok('all 5 viz hosts hidden and empty', s.hosts.length === 5 && s.hosts.every(Boolean))
  ok('atmosphere bar still readable text', s.bar > 20)
  ok('no mode control, no scene lab', !s.ctl && s.lab === 0)
  ok('readiness + 7-deck nav + hero markup present', s.rdy && s.nav === 7 && s.hero)
  for (const v of ['deck', 'train', 'log', 'itt', 'engine', 'atlas', 'body']) {
    await c.eval(`setView('${v}',{push:true})`); await sleep(v === 'atlas' ? 2000 : v === 'itt' ? 2500 : 500)
    const t = await c.eval(`({on: document.querySelector('#content .view.is-on').dataset.view, hash: location.hash, ov: document.documentElement.scrollWidth - innerWidth})`)
    ok(`no-fx view ${v}`, t.on === v && t.hash === '#' + v && t.ov <= 0, JSON.stringify(t))
  }
  ok('no-fx: itt plates built', await c.eval(`!!(window.__tsv && __tsv.items.length)`))
  ok('no-fx: atlas ready', await c.eval('AT.ready === true'))
  await c.eval(`setView('train',{push:true})`); await sleep(300)
  const ses = await c.eval(`(document.querySelector('.ses[data-ses]')||{}).dataset.ses`)
  const t0 = Date.now(); await c.eval(`openSessionDrawer('${ses}')`)
  const opened = await c.waitFor(`document.getElementById('drawer').classList.contains('open')`, 4000, 100)
  ok('no-fx: drawer opens', opened, 'ses=' + ses + ' after ' + (Date.now() - t0) + 'ms cls=' + await c.eval(`document.getElementById('drawer').className`))
  await c.eval('closeDrawer()'); await sleep(300)
  await c.eval(`setView('log',{push:true})`); await sleep(600)
  await c.eval(`document.querySelector('.act-detail-btn').click()`); await sleep(800)
  ok('no-fx: activity modal opens', await c.eval(`!!document.querySelector('.am-overlay.open')`))
  await c.eval(`setView('deck',{push:true})`); await sleep(800)
  await c.shot(path.join(OUT, 'nofx-overview.png'))
  res.console = res.console.filter(x => !/favicon|jsdelivr|steve-quotes|ERR_BLOCKED_BY_CLIENT|net::/i.test(x))
  ok('no-fx: no console errors', res.console.length === 0, res.console.slice(0, 4).join(' | '))
  // ── (2) data fetch failure
  console.log('## strava.json blocked')
  res.console = []
  await c.send('Network.setBlockedURLs', { urls: ['*data/strava.json*'] })
  await c.goto('http://127.0.0.1:8765/strava_fable51.html'); await sleep(4000)
  const e = await c.eval(`({msg: document.getElementById('content').textContent.trim().slice(0, 60), fx: !!window.__fx, atmHidden: !document.getElementById('atm') || document.getElementById('atm').hidden, ctl: !!document.querySelector('.fxm'), nav: document.querySelectorAll('.nav-i').length})`)
  ok('fetch failure shows existing Data unavailable message', /Data unavailable/.test(e.msg), e.msg)
  ok('fetch failure: fx loaded but atmosphere stays hidden, chrome control present', e.fx && e.atmHidden && e.ctl, JSON.stringify(e))
  res.console = res.console.filter(x => !/favicon|jsdelivr|steve-quotes|ERR_BLOCKED_BY_CLIENT|net::|strava.json/i.test(x))
  ok('fetch failure: no fx exceptions', res.console.length === 0, res.console.slice(0, 4).join(' | '))
  console.log(JSON.stringify({ pass: res.pass.length, fail: res.fail.length }))
  fs.writeFileSync(path.join(OUT, 'nofx-report.json'), JSON.stringify(res, null, 1))
  c.close(); chrome.kill(); process.exit(0)
})().catch(e => { console.log('NOFX CRASH', e); process.exit(2) })
